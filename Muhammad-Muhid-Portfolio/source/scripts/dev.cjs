const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const build = () => spawnSync(process.execPath,[path.join(__dirname,'build.cjs')],{stdio:'inherit'});
if (build().status !== 0) process.exit(1);
require('./serve.cjs');
let timer;
const recompile = () => { clearTimeout(timer); timer = setTimeout(() => { build(); console.log('Rebuilt. Refresh your browser to see the changes.'); },160); };
for (const dir of ['src','public']) fs.watch(path.join(__dirname,'..',dir),{recursive:true},recompile);
fs.watch(path.join(__dirname,'..','index.html'),recompile);
